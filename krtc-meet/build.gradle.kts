// iOS simulator app without an Xcode project: the Kotlin executable (UIApplicationMain + ComposeUIViewController,
// iosMain/Main.ios.kt) with an Info.plist, ad-hoc signed. Install: xcrun simctl install booted <app>.
val iosSimulatorAppDir = layout.buildDirectory.dir("ios/krtc-meet.app")
val iosSimulatorAppFiles = tasks.register<Sync>("iosSimulatorAppFiles") {
    from(tasks.named("linkDebugExecutableIosSimulatorArm64")) {
        include("krtc-meet.kexe")
        rename { "krtc-meet" }
        filePermissions { unix("rwxr-xr-x") }
    }
    from("src/iosMain/Info.plist")
    into(iosSimulatorAppDir)
}
tasks.register<Exec>("assembleIosSimulatorApp") {
    group = "build"
    dependsOn(iosSimulatorAppFiles)
    inputs.dir(iosSimulatorAppDir)
    commandLine("codesign", "--force", "--sign", "-", iosSimulatorAppDir.get().asFile.absolutePath)
}

// The desktop app's jars in one directory, to run it with plain java (classpath: that directory's jars,
// main class krtc.meet.MainKt).
tasks.register<Sync>("desktopClasspath") {
    from(tasks.named("jvmJar"))
    from(configurations.named("jvmRuntimeClasspath"))
    into(layout.buildDirectory.dir("desktop-classpath"))
}

// Tests log to the build directory, not to the user's ~/.krtc-meet.
tasks.withType<Test>().configureEach {
    systemProperty("krtc.meet.logDir", layout.buildDirectory.dir("test-logs").get().asFile.absolutePath)
    systemProperty("krtc.meet.settingsDir", layout.buildDirectory.dir("test-settings").get().asFile.absolutePath)
}

// macOS keeps Screen Recording, Camera and Microphone permissions per code signature. With a stable identity
// (tools/macos/create-signing-identity.sh, or a Developer ID) every build keeps them; ad-hoc signing, the default,
// changes with every build and macOS asks again. -Pkrtc.macos.signIdentity=<name or SHA-1>; krtc.macos.signKeychain
// picks a keychain file (CI).
val macSignIdentity = (findProperty("krtc.macos.signIdentity") as String?) ?: System.getenv("KRTC_MACOS_SIGN_IDENTITY")
val macSignKeychain = (findProperty("krtc.macos.signKeychain") as String?) ?: System.getenv("KRTC_MACOS_SIGN_KEYCHAIN")
if (macSignIdentity != null) {
    val macApp = layout.buildDirectory.dir("compose/binaries/main/app/krtc-meet.app")
    val signMacApp = tasks.register<Exec>("signMacApp") {
        group = "build"
        description = "Signs krtc-meet.app with a stable identity, so macOS keeps its permissions across builds"
        dependsOn("createDistributable")
        val keychain = macSignKeychain?.let { listOf("--keychain", it) }.orEmpty()
        commandLine(listOf("codesign", "--force", "--deep", "--timestamp=none", "--sign", macSignIdentity) + keychain + macApp.get().asFile.absolutePath)
    }
    tasks.matching { it.name == "createDistributable" }.configureEach { finalizedBy(signMacApp) }
    tasks.matching { it.name == "packageDmg" }.configureEach { dependsOn(signMacApp) }
}
